//! `HTML/CSS` deterministic generator — ports OpenPencil's `@open-pencil/dom-css`
//! HTML + CSS export onto canonical `PenDocument` / `PenNode` trees.
//!
//! Emits clean semantic HTML with inline/stylesheet CSS rules (flexbox, sizing,
//! padding, gap, colors, gradients, borders, shadows, typography, and CSS custom
//! properties from `doc.variables`).

use crate::design_jsx::resolve_target_nodes;
use crate::tailwind_jsx::semantic_html_tag;
use crate::{
    color_to_css, fmt_num, html_escape, node_children, node_hidden, root_nodes, Codegen,
    CssVariables,
};
use jian_ops_schema::node::text::FontStyleKind;
use jian_ops_schema::node::{
    AlignItems, CornerRadius, FontWeight, ImageFitMode, JustifyContent, LayoutMode,
    NumberOrExpression, Padding, PenNode, TextAlign, TextContent,
};
use jian_ops_schema::sizing::{SizingBehavior, SizingKeyword};
use jian_ops_schema::style::{PenEffect, PenFill, StrokeThickness};
use jian_ops_schema::PenDocument;
use op_editor_core::pen_node_ext::PenNodeExt;

/// Deterministic `HTML/CSS` generator.
pub struct HtmlCss;

impl Codegen for HtmlCss {
    fn target_label(&self) -> &'static str {
        "html-css"
    }

    fn generate(&self, doc: &PenDocument) -> String {
        generate_html_css_for_nodes(doc, root_nodes(doc))
    }
}

/// Generate `HTML/CSS` for an explicit slice of `PenNode`s.
pub fn generate_html_css_for_nodes(doc: &PenDocument, nodes: &[PenNode]) -> String {
    let refs: Vec<&PenNode> = nodes.iter().collect();
    generate_html_css_for_node_refs(doc, &refs)
}

/// Generate `HTML/CSS` for selected node IDs (or active page roots when empty).
pub fn generate_html_css_selection(
    doc: &PenDocument,
    page_roots: &[PenNode],
    selected_ids: &[String],
) -> String {
    let targets = resolve_target_nodes(page_roots, selected_ids);
    generate_html_css_for_node_refs(doc, &targets)
}

pub fn generate_html_css_for_node_refs(doc: &PenDocument, nodes: &[&PenNode]) -> String {
    let mut out = String::new();
    if doc.variables.as_ref().is_some_and(|v| !v.is_empty()) {
        let vars_css = CssVariables.generate(doc);
        let trimmed = vars_css
            .strip_prefix("/* Generated by OpenPencil — codegen::CssVariables */\n")
            .unwrap_or(&vars_css)
            .trim();
        if !trimmed.is_empty() {
            out.push_str("<style>\n");
            out.push_str(trimmed);
            out.push_str("\n</style>\n\n");
        }
    }
    let mut blocks = Vec::new();
    for node in nodes {
        let mut block = String::new();
        emit_html_css_node(doc, node, None, 0, &mut block);
        let trimmed = block.trim_end();
        if !trimmed.is_empty() {
            blocks.push(trimmed.to_string());
        }
    }
    if !blocks.is_empty() {
        out.push_str(&blocks.join("\n\n"));
        out.push('\n');
    }
    out
}

fn css_value_or_var(raw: &str) -> String {
    let t = raw.trim();
    if let Some(var_name) = t.strip_prefix('$') {
        let css_var = if var_name.starts_with("--") {
            var_name.to_string()
        } else {
            format!("--{var_name}")
        };
        return format!("var({css_var})");
    }
    color_to_css(t)
}

fn push_sizing_css(
    styles: &mut Vec<String>,
    width: &Option<SizingBehavior>,
    height: &Option<SizingBehavior>,
    parent: Option<&PenNode>,
    is_text: bool,
) {
    let parent_layout = parent.and_then(|p| match p {
        PenNode::Frame(f) => f.container.layout.clone(),
        PenNode::Group(g) => g.container.layout.clone(),
        PenNode::Rectangle(r) => r.container.layout.clone(),
        _ => None,
    });
    match width {
        Some(SizingBehavior::Keyword(SizingKeyword::FillContainer)) => {
            if matches!(parent_layout, Some(LayoutMode::Horizontal)) {
                styles.push("flex: 1 1 0%".into());
                styles.push("min-width: 0".into());
            } else {
                styles.push("width: 100%".into());
            }
        }
        Some(SizingBehavior::Keyword(SizingKeyword::FitContent)) => {
            if !is_text {
                styles.push("width: fit-content".into());
            }
        }
        Some(SizingBehavior::Number(w)) if *w > 0.0 => {
            styles.push(format!("width: {}px", fmt_num(*w)));
        }
        Some(SizingBehavior::Expression(expr)) => {
            styles.push(format!("width: {}", css_value_or_var(expr)));
        }
        _ => {}
    }

    match height {
        Some(SizingBehavior::Keyword(SizingKeyword::FillContainer)) => {
            if matches!(parent_layout, Some(LayoutMode::Vertical)) {
                styles.push("flex: 1 1 0%".into());
                styles.push("min-height: 0".into());
            } else {
                styles.push("height: 100%".into());
            }
        }
        Some(SizingBehavior::Keyword(SizingKeyword::FitContent)) => {
            if !is_text {
                styles.push("height: fit-content".into());
            }
        }
        Some(SizingBehavior::Number(h)) if *h > 0.0 => {
            styles.push(format!("height: {}px", fmt_num(*h)));
        }
        Some(SizingBehavior::Expression(expr)) => {
            styles.push(format!("height: {}", css_value_or_var(expr)));
        }
        _ => {}
    }
}

fn push_padding_css(styles: &mut Vec<String>, padding: &Option<Padding>) {
    match padding {
        Some(Padding::Uniform(v)) if *v > 0.0 => {
            styles.push(format!("padding: {}px", fmt_num(*v)));
        }
        Some(Padding::XY([py, px])) => {
            if *py > 0.0 || *px > 0.0 {
                styles.push(format!("padding: {}px {}px", fmt_num(*py), fmt_num(*px)));
            }
        }
        Some(Padding::LtrB([pt, pr, pb, pl])) => {
            if *pt > 0.0 || *pr > 0.0 || *pb > 0.0 || *pl > 0.0 {
                styles.push(format!(
                    "padding: {}px {}px {}px {}px",
                    fmt_num(*pt),
                    fmt_num(*pr),
                    fmt_num(*pb),
                    fmt_num(*pl)
                ));
            }
        }
        Some(Padding::Expression(expr)) => {
            styles.push(format!("padding: {}", css_value_or_var(expr)));
        }
        _ => {}
    }
}

fn push_corner_css(styles: &mut Vec<String>, radius: &Option<CornerRadius>) {
    match radius {
        Some(CornerRadius::Uniform(r)) if *r > 0.0 => {
            styles.push(format!("border-radius: {}px", fmt_num(*r)));
        }
        Some(CornerRadius::PerCorner([tl, tr, br, bl])) => {
            if *tl > 0.0 || *tr > 0.0 || *br > 0.0 || *bl > 0.0 {
                styles.push(format!(
                    "border-radius: {}px {}px {}px {}px",
                    fmt_num(*tl),
                    fmt_num(*tr),
                    fmt_num(*br),
                    fmt_num(*bl)
                ));
            }
        }
        _ => {}
    }
}

fn push_fill_css(styles: &mut Vec<String>, fills: Option<&Vec<PenFill>>, is_text: bool) {
    let Some(fills) = fills else {
        return;
    };
    let prop = if is_text { "color" } else { "background" };
    for fill in fills {
        match fill {
            PenFill::Solid(s) => {
                styles.push(format!("{prop}: {}", css_value_or_var(&s.color)));
                return;
            }
            PenFill::LinearGradient(g) => {
                let stops: Vec<String> = g
                    .stops
                    .iter()
                    .map(|st| {
                        format!(
                            "{} {}%",
                            css_value_or_var(&st.color),
                            fmt_num((st.offset * 100.0) as f64)
                        )
                    })
                    .collect();
                let deg = g.angle.unwrap_or(180.0) as f64;
                styles.push(format!(
                    "background: linear-gradient({}deg, {})",
                    fmt_num(deg),
                    stops.join(", ")
                ));
                return;
            }
            _ => {}
        }
    }
}

fn push_stroke_css(styles: &mut Vec<String>, stroke: Option<&jian_ops_schema::style::PenStroke>) {
    let Some(stroke) = stroke else {
        return;
    };
    let color = stroke
        .fill
        .as_ref()
        .and_then(|fills| {
            fills.iter().find_map(|f| match f {
                PenFill::Solid(s) => Some(css_value_or_var(&s.color)),
                _ => None,
            })
        })
        .unwrap_or_else(|| "#000000".to_string());
    let style_kw = if stroke.dash_pattern.as_ref().is_some_and(|d| !d.is_empty()) {
        "dashed"
    } else {
        "solid"
    };
    match &stroke.thickness {
        StrokeThickness::Uniform(w) if *w > 0.0 => {
            styles.push(format!(
                "border: {}px {style_kw} {color}",
                fmt_num(*w as f64)
            ));
        }
        StrokeThickness::PerSide([t, r, b, l]) => {
            if *t > 0.0 {
                styles.push(format!(
                    "border-top: {}px {style_kw} {color}",
                    fmt_num(*t as f64)
                ));
            }
            if *r > 0.0 {
                styles.push(format!(
                    "border-right: {}px {style_kw} {color}",
                    fmt_num(*r as f64)
                ));
            }
            if *b > 0.0 {
                styles.push(format!(
                    "border-bottom: {}px {style_kw} {color}",
                    fmt_num(*b as f64)
                ));
            }
            if *l > 0.0 {
                styles.push(format!(
                    "border-left: {}px {style_kw} {color}",
                    fmt_num(*l as f64)
                ));
            }
        }
        StrokeThickness::Sided(s) => {
            if let Some(t) = s.top.filter(|v| *v > 0.0) {
                styles.push(format!(
                    "border-top: {}px {style_kw} {color}",
                    fmt_num(t as f64)
                ));
            }
            if let Some(r) = s.right.filter(|v| *v > 0.0) {
                styles.push(format!(
                    "border-right: {}px {style_kw} {color}",
                    fmt_num(r as f64)
                ));
            }
            if let Some(b) = s.bottom.filter(|v| *v > 0.0) {
                styles.push(format!(
                    "border-bottom: {}px {style_kw} {color}",
                    fmt_num(b as f64)
                ));
            }
            if let Some(l) = s.left.filter(|v| *v > 0.0) {
                styles.push(format!(
                    "border-left: {}px {style_kw} {color}",
                    fmt_num(l as f64)
                ));
            }
        }
        _ => {}
    }
}

fn push_effect_css(styles: &mut Vec<String>, effects: Option<&Vec<PenEffect>>) {
    let Some(effects) = effects else {
        return;
    };
    for effect in effects {
        match effect {
            PenEffect::Shadow(s) if s.visible != Some(false) => {
                let inset = if s.inner == Some(true) { "inset " } else { "" };
                styles.push(format!(
                    "box-shadow: {}{}px {}px {}px {}px {}",
                    inset,
                    fmt_num(s.offset_x as f64),
                    fmt_num(s.offset_y as f64),
                    fmt_num(s.blur as f64),
                    fmt_num(s.spread as f64),
                    css_value_or_var(&s.color)
                ));
            }
            PenEffect::Blur(b) if b.visible != Some(false) && b.radius > 0.0 => {
                styles.push(format!("filter: blur({}px)", fmt_num(b.radius as f64)));
            }
            PenEffect::BackgroundBlur(b) if b.visible != Some(false) && b.radius > 0.0 => {
                styles.push(format!(
                    "backdrop-filter: blur({}px)",
                    fmt_num(b.radius as f64)
                ));
            }
            _ => {}
        }
    }
}

fn push_container_css(
    styles: &mut Vec<String>,
    container: &jian_ops_schema::node::ContainerProps,
    has_children: bool,
    parent: Option<&PenNode>,
) {
    match container.layout {
        Some(LayoutMode::Horizontal) => {
            styles.push("display: flex".into());
            styles.push("flex-direction: row".into());
        }
        Some(LayoutMode::Vertical) => {
            styles.push("display: flex".into());
            styles.push("flex-direction: column".into());
        }
        _ => {
            if has_children {
                styles.push("position: relative".into());
            }
        }
    }
    push_sizing_css(styles, &container.width, &container.height, parent, false);
    if let Some(min_w) = container.limits.min_width {
        styles.push(format!("min-width: {}px", fmt_num(min_w)));
    }
    if let Some(max_w) = container.limits.max_width {
        styles.push(format!("max-width: {}px", fmt_num(max_w)));
    }
    if let Some(min_h) = container.limits.min_height {
        styles.push(format!("min-height: {}px", fmt_num(min_h)));
    }
    if let Some(max_h) = container.limits.max_height {
        styles.push(format!("max-height: {}px", fmt_num(max_h)));
    }
    match &container.gap {
        Some(NumberOrExpression::Number(g)) if *g > 0.0 => {
            styles.push(format!("gap: {}px", fmt_num(*g)));
        }
        Some(NumberOrExpression::Expression(expr)) => {
            styles.push(format!("gap: {}", css_value_or_var(expr)));
        }
        _ => {}
    }
    push_padding_css(styles, &container.padding);
    match container.justify_content {
        Some(JustifyContent::Center) => styles.push("justify-content: center".into()),
        Some(JustifyContent::End) => styles.push("justify-content: flex-end".into()),
        Some(JustifyContent::SpaceBetween) => styles.push("justify-content: space-between".into()),
        Some(JustifyContent::SpaceAround) => styles.push("justify-content: space-around".into()),
        _ => {}
    }
    match container.align_items {
        Some(AlignItems::Start) => styles.push("align-items: flex-start".into()),
        Some(AlignItems::Center) => styles.push("align-items: center".into()),
        Some(AlignItems::End) => styles.push("align-items: flex-end".into()),
        Some(AlignItems::Stretch) => styles.push("align-items: stretch".into()),
        None => {}
    }
    push_fill_css(styles, container.fill.as_ref(), false);
    push_stroke_css(styles, container.stroke.as_ref());
    push_corner_css(styles, &container.corner_radius);
    if container.clip_content == Some(true) {
        styles.push("overflow: hidden".into());
    }
    push_effect_css(styles, container.effects.as_ref());
}

fn emit_html_css_node(
    doc: &PenDocument,
    node: &PenNode,
    parent: Option<&PenNode>,
    depth: usize,
    out: &mut String,
) {
    if node_hidden(node) {
        return;
    }
    let indent = "  ".repeat(depth);
    let base = node.base();
    let mut styles: Vec<String> = Vec::new();

    let placed_absolutely = parent.is_some_and(|p| !p.is_auto_layout_container());
    if placed_absolutely {
        styles.push("position: absolute".into());
        styles.push(format!("left: {}px", fmt_num(base.x.unwrap_or(0.0))));
        styles.push(format!("top: {}px", fmt_num(base.y.unwrap_or(0.0))));
    }
    if let Some(rot) = base.rotation.filter(|v| v.abs() > f64::EPSILON) {
        styles.push(format!("transform: rotate({}deg)", fmt_num(rot)));
    }
    if let Some(NumberOrExpression::Number(op)) = base.opacity {
        if (op - 1.0).abs() > f64::EPSILON {
            styles.push(format!("opacity: {}", fmt_num(op)));
        }
    }

    let mut data_name = base
        .name
        .as_deref()
        .filter(|n| !n.trim().is_empty())
        .map(|n| format!(" data-name=\"{}\"", html_escape(n)))
        .unwrap_or_default();
    if let Some(a11y_label) = op_editor_core::command_node_attrs::node_semantics(node)
        .and_then(|s| s.label.as_deref())
        .filter(|l| !l.trim().is_empty())
    {
        data_name.push_str(&format!(" aria-label=\"{}\"", html_escape(a11y_label)));
    }
    if let Some(explain) = base
        .explain
        .as_deref()
        .or_else(|| {
            op_editor_core::command_node_attrs::node_semantics(node)
                .and_then(|s| s.ai_description.as_deref())
        })
        .filter(|e| !e.trim().is_empty())
    {
        out.push_str(&format!(
            "{indent}<!-- @design-note: {} -->\n",
            explain.replace("-->", "-- >")
        ));
    }

    let children = node_children(node);
    match node {
        PenNode::Frame(n) => {
            push_container_css(&mut styles, &n.container, !children.is_empty(), parent)
        }
        PenNode::Group(n) => {
            push_container_css(&mut styles, &n.container, !children.is_empty(), parent)
        }
        PenNode::Rectangle(n) => {
            push_container_css(&mut styles, &n.container, !children.is_empty(), parent)
        }
        PenNode::Ellipse(n) => {
            push_sizing_css(&mut styles, &n.width, &n.height, parent, false);
            styles.push("border-radius: 50%".into());
            push_fill_css(&mut styles, n.fill.as_ref(), false);
            push_stroke_css(&mut styles, n.stroke.as_ref());
            push_effect_css(&mut styles, n.effects.as_ref());
        }
        PenNode::Image(n) => {
            push_sizing_css(&mut styles, &n.width, &n.height, parent, false);
            push_corner_css(&mut styles, &n.corner_radius);
            let fit = match n.object_fit {
                Some(ImageFitMode::Fit) => "contain",
                Some(ImageFitMode::Tile) => "none",
                _ => "cover",
            };
            styles.push(format!("object-fit: {fit}"));
            let style_attr = format!(" style=\"{}\"", styles.join("; "));
            let alt = base.name.as_deref().unwrap_or_default();
            out.push_str(&format!(
                "{indent}<img{data_name} src=\"{}\" alt=\"{}\"{style_attr}>\n",
                html_escape(n.src.as_ref()),
                html_escape(alt),
            ));
            return;
        }
        PenNode::IconFont(n) => {
            push_sizing_css(&mut styles, &n.width, &n.height, parent, false);
            push_fill_css(&mut styles, n.fill.as_ref(), true);
            let style_attr = if styles.is_empty() {
                String::new()
            } else {
                format!(" style=\"{}\"", styles.join("; "))
            };
            out.push_str(&format!(
                "{indent}<span{data_name} data-icon=\"{}\"{style_attr} aria-hidden=\"true\"></span>\n",
                html_escape(&n.icon_font_name),
            ));
            return;
        }
        PenNode::Path(n) => {
            let w = node.width_px().unwrap_or(24.0);
            let h = node.height_px().unwrap_or(24.0);
            push_sizing_css(&mut styles, &n.width, &n.height, parent, false);
            let style_attr = if styles.is_empty() {
                String::new()
            } else {
                format!(" style=\"{}\"", styles.join("; "))
            };
            let fill_color = n
                .fill
                .as_ref()
                .and_then(|fills| {
                    fills.iter().find_map(|f| match f {
                        PenFill::Solid(s) => Some(s.color.as_str()),
                        _ => None,
                    })
                })
                .unwrap_or("currentColor");
            let d = n.d.as_deref().unwrap_or_default();
            out.push_str(&format!(
                "{indent}<svg{data_name} viewBox=\"0 0 {} {}\" fill=\"none\"{style_attr}>\n{indent}  <path d=\"{}\" fill=\"{}\"></path>\n{indent}</svg>\n",
                fmt_num(w),
                fmt_num(h),
                html_escape(d),
                html_escape(fill_color),
            ));
            return;
        }
        PenNode::Text(n) => {
            styles.push("margin: 0".into());
            push_sizing_css(&mut styles, &n.width, &n.height, parent, true);
            if let Some(font) = n.font_family.as_deref() {
                styles.push(format!("font-family: {font}"));
            }
            if let Some(size) = n.font_size {
                styles.push(format!("font-size: {}px", fmt_num(size)));
            }
            match &n.font_weight {
                Some(FontWeight::Number(w)) if *w != 400 => {
                    styles.push(format!("font-weight: {w}"));
                }
                Some(FontWeight::Keyword(k)) if k != "normal" && k != "regular" => {
                    styles.push(format!("font-weight: {k}"));
                }
                _ => {}
            }
            if matches!(n.font_style, Some(FontStyleKind::Italic)) {
                styles.push("font-style: italic".into());
            }
            if let Some(lh) = n.line_height {
                styles.push(format!("line-height: {}", fmt_num(lh)));
            }
            if let Some(ls) = n.letter_spacing.filter(|v| v.abs() > f64::EPSILON) {
                styles.push(format!("letter-spacing: {}px", fmt_num(ls)));
            }
            match n.text_align {
                Some(TextAlign::Center) => styles.push("text-align: center".into()),
                Some(TextAlign::Right) => styles.push("text-align: right".into()),
                Some(TextAlign::Justify) => styles.push("text-align: justify".into()),
                _ => {}
            }
            push_fill_css(&mut styles, n.fill.as_ref(), true);

            let style_attr = if styles.is_empty() {
                String::new()
            } else {
                format!(" style=\"{}\"", styles.join("; "))
            };
            let content = match &n.content {
                TextContent::Plain(s) => html_escape(s),
                TextContent::Styled(segs) => segs
                    .iter()
                    .map(|seg| html_escape(&seg.text))
                    .collect::<String>(),
            };
            out.push_str(&format!(
                "{indent}<p{data_name}{style_attr}>{content}</p>\n"
            ));
            return;
        }
        _ => {
            if let Some(w) = node.width_px() {
                styles.push(format!("width: {}px", fmt_num(w)));
            }
            if let Some(h) = node.height_px() {
                styles.push(format!("height: {}px", fmt_num(h)));
            }
        }
    }

    let tag = semantic_html_tag(node);
    let style_attr = if styles.is_empty() {
        String::new()
    } else {
        format!(" style=\"{}\"", styles.join("; "))
    };
    if children.is_empty() {
        out.push_str(&format!("{indent}<{tag}{data_name}{style_attr}></{tag}>\n"));
    } else {
        out.push_str(&format!("{indent}<{tag}{data_name}{style_attr}>\n"));
        for child in children {
            emit_html_css_node(doc, child, Some(node), depth + 1, out);
        }
        out.push_str(&format!("{indent}</{tag}>\n"));
    }
}
