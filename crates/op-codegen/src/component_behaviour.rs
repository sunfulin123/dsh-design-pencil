//! Functional component exports share the preview compiler, state bindings and
//! canonical reference expansion; there is no codegen-only component resolver.

use std::collections::BTreeMap;

use jian_ops_schema::component::{BehaviourDefinition, BehaviourKind};
use jian_ops_schema::{node::PenNode, PenDocument};
use op_editor_core::component_behaviour::{
    behaviour_for_node, compile_component_behaviour, document_nodes, state_key, CONTROL_SUFFIX,
};
use op_editor_core::PenNodeExt;
use serde_json::{json, Value};

use crate::html_escape;

type Emitter = fn(&PenDocument, &PenNode, Option<&PenNode>, usize, &mut String);

fn function_name(id: &str) -> String {
    format!(
        "OpBehaviour{}",
        state_key(id).trim_start_matches("__component_")
    )
}

fn collect<'a>(
    doc: &'a PenDocument,
    nodes: &[&'a PenNode],
    out: &mut BTreeMap<String, &'a PenNode>,
) {
    for node in nodes {
        if behaviour_for_node(doc, node).is_some() {
            out.insert(node.id_str().to_owned(), node);
        } else if let Some(children) = node.children() {
            collect(doc, &children.iter().collect::<Vec<_>>(), out);
        }
    }
}

pub(crate) fn generate_jsx(doc: &PenDocument, nodes: &[&PenNode], emit: Emitter) -> Option<String> {
    let mut owners = BTreeMap::new();
    collect(doc, nodes, &mut owners);
    if owners.is_empty() {
        return None;
    }
    let compiled = match compile_component_behaviour(doc) {
        Ok(doc) => doc,
        Err(error) => {
            return Some(format!(
                "/* Component behaviour export failed: {} */\n",
                error.to_string().replace("*/", "* /")
            ))
        }
    };
    let resolved = document_nodes(&compiled);
    let mut body = String::new();
    for node in nodes {
        emit(doc, node, None, 2, &mut body);
    }
    let mut out = format!(
        "import {{ useState }} from 'react';\n\nexport default function Design() {{\n  return <>\n{body}  </>;\n}}\n"
    );
    for (id, original) in owners {
        let Some(node) = resolved.get(&id) else {
            continue;
        };
        let behaviour = behaviour_for_node(doc, original).unwrap();
        let visual = visual_markup(&compiled, node, emit);
        let control = jsx_control(&id, original, behaviour, &visual);
        out.push_str(&format!("\nfunction {}({{style}}) {{\n  const [value, setValue] = useState({});\n  return (\n<div style={{style}}>{control}</div>\n  );\n}}\n",
            function_name(&id), js(&behaviour.default_value)));
    }
    Some(out)
}

fn visual_markup(doc: &PenDocument, node: &PenNode, emit: Emitter) -> String {
    let mut out = String::new();
    if let Some(children) = node.children() {
        for child in children {
            if !child.id_str().ends_with(CONTROL_SUFFIX) {
                emit(doc, child, Some(node), 0, &mut out);
            }
        }
    }
    out
}

pub(crate) fn emit_component(
    doc: &PenDocument,
    node: &PenNode,
    parent: Option<&PenNode>,
    jsx: bool,
    out: &mut String,
    emit: Emitter,
) -> bool {
    let Some(behaviour) = behaviour_for_node(doc, node) else {
        return false;
    };
    if jsx {
        let compiled = match compile_component_behaviour(doc) {
            Ok(doc) => doc,
            Err(error) => {
                out.push_str(&format!(
                    "{{/* {} */}}\n",
                    error.to_string().replace("*/", "* /")
                ));
                return true;
            }
        };
        let nodes = document_nodes(&compiled);
        let resolved = nodes.get(node.id_str()).copied().unwrap_or(node);
        out.push_str(&format!(
            "<{} style={{{}}} />\n",
            function_name(node.id_str()),
            js(&geometry(resolved, parent))
        ));
        return true;
    }
    let compiled = match compile_component_behaviour(doc) {
        Ok(doc) => doc,
        Err(error) => {
            out.push_str(&format!(
                "<!-- Component behaviour export failed: {} -->",
                html_escape(&error.to_string()).replace("--", "—")
            ));
            return true;
        }
    };
    let nodes = document_nodes(&compiled);
    let Some(resolved) = nodes.get(node.id_str()) else {
        return true;
    };
    let visual = visual_markup(&compiled, resolved, emit);
    out.push_str(&html_control(
        node.id_str(),
        node,
        behaviour,
        &visual,
        resolved,
        parent,
    ));
    true
}

/// Bindings are generated by the shared compiler, never evaluated with `eval`
/// or parsed by a second expression engine in the exported application.
pub(crate) fn emit_bound(
    doc: &PenDocument,
    node: &PenNode,
    parent: Option<&PenNode>,
    depth: usize,
    jsx: bool,
    out: &mut String,
    emit: Emitter,
) -> bool {
    let Ok(mut value) = serde_json::to_value(node) else {
        return false;
    };
    let Some(bindings) = value.get("bindings").and_then(Value::as_object) else {
        return false;
    };
    let binding = |key| {
        bindings
            .get(key)
            .and_then(Value::as_str)
            .filter(|s| s.contains("$state.__component_"))
            .map(str::to_owned)
    };
    let visible = binding("visible");
    let content = binding("content");
    if visible.is_none() && content.is_none() {
        return false;
    }
    value.as_object_mut().unwrap().remove("bindings");
    value["visible"] = json!(true);
    let Ok(clean) = serde_json::from_value::<PenNode>(value) else {
        return false;
    };
    let mut markup = String::new();
    emit(doc, &clean, parent, depth, &mut markup);
    if let Some(expression) = content {
        if let (Some(start), Some(end)) = (markup.find('>'), markup.rfind("</")) {
            let replacement = if jsx {
                format!("{{{}}}", js_expression(&expression))
            } else {
                String::new()
            };
            if start < end {
                markup.replace_range(start + 1..end, &replacement);
            }
        }
        if !jsx {
            add_attribute(&mut markup, "data-op-content", &expression);
        }
    }
    if let Some(expression) = visible {
        if jsx {
            markup = format!("{{{} && (<>{markup}</>)}}\n", js_expression(&expression));
        } else {
            add_attribute(&mut markup, "data-op-visible", &expression);
        }
    }
    out.push_str(&markup);
    true
}

fn add_attribute(markup: &mut String, key: &str, value: &str) {
    if let Some(end) = markup.find('>') {
        markup.insert_str(end, &format!(" {key}=\"{}\"", html_escape(value)));
    }
}

fn js_expression(expression: &str) -> String {
    let mut expression = expression.to_owned();
    while let Some(start) = expression.find("$state.__component_") {
        let tail = &expression[start + "$state.__component_".len()..];
        let digits = tail.bytes().take_while(u8::is_ascii_hexdigit).count();
        expression.replace_range(start..start + "$state.__component_".len() + digits, "value");
    }
    expression
}

fn js(value: &Value) -> String {
    value
        .to_string()
        .replace('<', "\\u003c")
        .replace('\u{2028}', "\\u2028")
        .replace('\u{2029}', "\\u2029")
}

fn label(node: &PenNode) -> String {
    html_escape(node.base().name.as_deref().unwrap_or(node.id_str()))
}

fn geometry(node: &PenNode, parent: Option<&PenNode>) -> Value {
    let (width, height) = crate::node_size(node);
    let absolute = parent.is_some_and(|parent| !parent.is_auto_layout_container());
    let mut style = json!({"position":if absolute {"absolute"}else{"relative"},
        "width":width,"height":height});
    if absolute {
        style["left"] = json!(node.base().x.unwrap_or(0.0));
        style["top"] = json!(node.base().y.unwrap_or(0.0));
    }
    style
}

fn jsx_control(id: &str, node: &PenNode, b: &BehaviourDefinition, visual: &str) -> String {
    let disabled = if b.disabled { " disabled" } else { "" };
    let common = format!(" aria-label=\"{}\"{disabled}", label(node));
    match b.kind {
        BehaviourKind::Button => format!("<button type=\"button\"{common} data-state={{value ? 'pressed' : 'rest'}} onPointerDown={{event => {{event.currentTarget.setPointerCapture(event.pointerId);setValue(true);}}}} onPointerUp={{() => setValue(false)}} onPointerCancel={{() => setValue(false)}} onBlur={{() => setValue(false)}} onKeyDown={{event => {{if(event.key === 'Enter' || event.key === ' ') setValue(true);}}}} onKeyUp={{() => setValue(false)}} style={{{{position:'relative',width:'100%',height:'100%',border:0,padding:0,background:'transparent'}}}}>{visual}</button>"),
        BehaviourKind::Switch | BehaviourKind::Checkbox => {
            let role = match b.kind {
                BehaviourKind::Switch => "switch",
                BehaviourKind::Checkbox => "checkbox",
                _ => "button",
            };
            let aria = if b.kind == BehaviourKind::Button { "pressed" } else { "checked" };
            format!("<button type=\"button\" role=\"{role}\"{common} aria-{aria}={{value}} onClick={{() => setValue(!value)}} style={{{{position:'relative',width:'100%',height:'100%',border:0,padding:0,background:'transparent'}}}}>\n{visual}</button>")
        }
        BehaviourKind::Slider => format!(
            "<div style={{{{position:'relative',width:'100%',height:'100%'}}}}>{visual}<input type=\"range\"{common} min={{{}}} max={{{}}} step={{{}}} value={{value}} aria-valuemin={{{}}} aria-valuemax={{{}}} aria-valuenow={{value}} onChange={{event => setValue(Number(event.target.value))}} style={{{{position:'absolute',inset:0,width:'100%',height:'100%',opacity:0}}}} /></div>",
            b.min.unwrap_or(0.0), b.max.unwrap_or(100.0), b.step.unwrap_or(1.0),
            b.min.unwrap_or(0.0), b.max.unwrap_or(100.0)),
        BehaviourKind::Tabs => {
            let panel = format!("{}Panel", function_name(id));
            let options = js(&json!(b.options.iter().map(|o| &o.value).collect::<Vec<_>>()));
            let mut tabs = String::new();
            for (index, option) in b.options.iter().enumerate() {
                let value = js(&json!(option.value));
                tabs.push_str(&format!(
                    "<button type=\"button\" role=\"tab\" id=\"{panel}Tab{index}\" aria-controls=\"{panel}\" aria-selected={{value === {value}}} tabIndex={{value === {value} ? 0 : -1}}{disabled} onClick={{() => setValue({value})}} onKeyDown={{event => {{ const keys = {options}; let i = keys.indexOf(value); if(event.key === 'ArrowRight') i = (i+1)%keys.length; else if(event.key === 'ArrowLeft') i = (i+keys.length-1)%keys.length; else if(event.key === 'Home') i=0; else if(event.key === 'End') i=keys.length-1; else return; event.preventDefault(); setValue(keys[i]); event.currentTarget.parentElement.children[i].focus(); }}}}>{}</button>",
                    html_escape(&option.label)));
            }
            format!("<div><div role=\"tablist\" aria-label=\"{}\">{tabs}</div><div role=\"tabpanel\" id=\"{panel}\" aria-labelledby={{{}.map((key,i) => key === value ? '{panel}Tab'+i : '').filter(Boolean).join(' ')}}>{visual}</div></div>", label(node), options)
        }
    }
}

fn html_control(
    id: &str,
    node: &PenNode,
    b: &BehaviourDefinition,
    visual: &str,
    resolved: &PenNode,
    parent: Option<&PenNode>,
) -> String {
    let owner = function_name(id);
    let disabled = if b.disabled { " disabled" } else { "" };
    let name = label(node);
    let default = html_escape(&b.default_value.to_string());
    let (markup, handlers) = match b.kind {
        BehaviourKind::Button => (
            format!("<button type=\"button\" aria-label=\"{name}\"{disabled} style=\"position:relative;width:100%;height:100%;border:0;padding:0;background:transparent\">{visual}</button>"),
            "const control=root.firstElementChild; const press=()=>{if(!control.disabled){value=true;update();}}; const release=()=>{value=false;update();};control.addEventListener('pointerdown',event=>{if(control.disabled)return;control.setPointerCapture(event.pointerId);press();});control.addEventListener('pointerup',release);control.addEventListener('pointercancel',release);control.addEventListener('blur',release);control.addEventListener('keydown',event=>{if(event.key==='Enter'||event.key===' ')press();});control.addEventListener('keyup',release);const sync=()=>control.dataset.state=value?'pressed':'rest';".to_owned()
        ),
        BehaviourKind::Switch | BehaviourKind::Checkbox => {
            let role = match b.kind {
                BehaviourKind::Switch => "switch",
                BehaviourKind::Checkbox => "checkbox",
                _ => "button",
            };
            let aria = if b.kind == BehaviourKind::Button {
                "pressed"
            } else {
                "checked"
            };
            (format!("<button type=\"button\" role=\"{role}\" aria-label=\"{name}\" aria-{aria}=\"{default}\"{disabled} style=\"position:relative;width:100%;height:100%;border:0;padding:0;background:transparent\">{visual}</button>"),
             format!("const control=root.firstElementChild; control.addEventListener('click',()=>{{if(control.disabled)return; value=!value; update();}}); const sync=()=>control.setAttribute('aria-{aria}',String(value));"))
        }
        BehaviourKind::Slider => {
            let (min, max, step) = (
                b.min.unwrap_or(0.0),
                b.max.unwrap_or(100.0),
                b.step.unwrap_or(1.0),
            );
            (format!("<div style=\"position:relative;width:100%;height:100%\">{visual}<input type=\"range\" aria-label=\"{name}\" min=\"{min}\" max=\"{max}\" step=\"{step}\" value=\"{default}\" aria-valuemin=\"{min}\" aria-valuemax=\"{max}\" aria-valuenow=\"{default}\"{disabled} style=\"position:absolute;inset:0;width:100%;height:100%;opacity:0\"></div>"),
             "const control=root.querySelector('input'); control.addEventListener('input',()=>{value=Number(control.value);update();}); const sync=()=>control.setAttribute('aria-valuenow',String(value));".to_owned())
        }
        BehaviourKind::Tabs => {
            let tabs = b.options.iter().enumerate().map(|(i,o)| {
                let active = b.default_value.as_str() == Some(&o.value);
                format!("<button type=\"button\" role=\"tab\" id=\"{owner}Tab{i}\" data-value=\"{}\" aria-controls=\"{owner}Panel\" aria-selected=\"{active}\" tabindex=\"{}\"{disabled}>{}</button>",
                    html_escape(&o.value),if active {0}else{-1},html_escape(&o.label))
            }).collect::<String>();
            (format!("<div role=\"tablist\" aria-label=\"{name}\">{tabs}</div><div role=\"tabpanel\" id=\"{owner}Panel\">{visual}</div>"),
             "const tabs=[...root.querySelectorAll('[role=tab]')]; tabs.forEach((tab,i)=>{tab.addEventListener('click',()=>{if(tab.disabled)return;value=tab.dataset.value;update();});tab.addEventListener('keydown',event=>{let next=i;if(event.key==='ArrowRight')next=(i+1)%tabs.length;else if(event.key==='ArrowLeft')next=(i+tabs.length-1)%tabs.length;else if(event.key==='Home')next=0;else if(event.key==='End')next=tabs.length-1;else return;event.preventDefault();if(!tabs[next].disabled){tabs[next].click();tabs[next].focus();}});});const sync=()=>tabs.forEach(tab=>{const selected=tab.dataset.value===value;tab.setAttribute('aria-selected',String(selected));tab.tabIndex=selected?0:-1;if(selected)root.querySelector('[role=tabpanel]').setAttribute('aria-labelledby',tab.id);});".to_owned())
        }
    };
    let mut expressions = BTreeMap::new();
    fn walk(node: &PenNode, out: &mut BTreeMap<String, String>) {
        if let Ok(value) = serde_json::to_value(node) {
            for expression in value
                .get("bindings")
                .and_then(Value::as_object)
                .into_iter()
                .flat_map(|b| b.values())
                .filter_map(Value::as_str)
            {
                if expression.contains("$state.__component_") {
                    out.insert(expression.to_owned(), js_expression(expression));
                }
            }
        }
        if let Some(children) = node.children() {
            for child in children {
                walk(child, out);
            }
        }
    }
    walk(resolved, &mut expressions);
    let functions = expressions
        .into_iter()
        .map(|(source, expression)| {
            format!(
                "{}:value=>({})",
                js(&json!(source)),
                expression.replace('<', "\\u003c")
            )
        })
        .collect::<Vec<_>>()
        .join(",");
    let geometry = geometry(resolved, parent);
    let style = geometry
        .as_object()
        .unwrap()
        .iter()
        .map(|(key, value)| {
            if let Some(value) = value.as_str() {
                format!("{key}:{value}")
            } else {
                format!("{key}:{value}px")
            }
        })
        .collect::<Vec<_>>()
        .join(";");
    format!("<div id=\"{owner}\" data-op-component=\"{}\" style=\"{style}\">{markup}</div>\n<script>(()=>{{const root=document.getElementById('{owner}');let value={};const expressions={{{functions}}};{handlers}function update(){{sync();root.querySelectorAll('[data-op-visible]').forEach(node=>{{node.hidden=!expressions[node.dataset.opVisible](value);}});root.querySelectorAll('[data-op-content]').forEach(node=>{{node.textContent=String(expressions[node.dataset.opContent](value));}});}}update();}})();</script>\n",
        html_escape(id), js(&b.default_value))
}
