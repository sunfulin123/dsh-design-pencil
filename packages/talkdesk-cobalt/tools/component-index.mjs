/** Generate source-first component guidance from authored MDX and actual exports/files. */
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { join, relative } from 'node:path';

async function codeFiles(root, directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (['__tests__', 'test'].includes(entry.name)) continue;
    const path = join(directory, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`Unexpected source link: ${path}`);
    if (entry.isDirectory()) files.push(...(await codeFiles(root, path)));
    else if (/\.(?:tsx?|css|jsx?)$/.test(path)) files.push(relative(root, path));
  }
  return files.toSorted();
}

export async function writeComponentIndexes(root, registry) {
  const exports = await readFile(join(root, 'components/extensions/src/index.ts'), 'utf8');
  const rows = [];
  for (const component of registry.components) {
    const slug = component.source.split('/').at(-1);
    const symbols = [
      ...exports.matchAll(/export(?: type)?\s*\{([^}]+)\}\s*from\s*['"]\.\/([^'"]+)['"]/g),
    ]
      .filter((match) => match[2] === slug)
      .flatMap((match) =>
        match[1]
          .split(',')
          .map((name) => name.trim())
          .filter(Boolean),
      );
    component.exports = symbols;
    component.reuse = 'copy-and-adapt-source';
    component.projectSource = `src/components/cobalt-extensions/${slug}`;
    component.sourceFiles = await codeFiles(root, join(root, component.source));
    const examples = component.examples.map((id) =>
      registry.examples.find((example) => example.id === id),
    );
    if (examples.some((example) => !example))
      throw new Error(`Missing example for ${component.id}`);
    const lines = [
      `# ${component.name} — Cobalt source template`,
      '',
      '<!-- Generated by tools/content.mjs from MDX and source; do not edit. -->',
      '',
      component.description,
      '',
      '## Copy and adapt',
      '',
      'This is editable source, not an installable library. Never install `@openpencil/cobalt-extensions` or import that package name. Official `@talkdesk/*` dependencies are separate.',
      '',
      `Before reuse, read the complete implementation, types, styles and local imports listed below. Use the HTML Skill lookup command with \`--id ${component.id} --read-source\` to read the source closure. Copy the templates into \`src/components/cobalt-extensions/\`, then import using a relative path to that project-local directory and adapt the implementation there.`,
      '',
      'Workspace creation copies the full tree. For a standalone/existing app, run the bundled `cobalt-project.mjs copy-source --out <project>`; it copies source without installing dependencies or replacing existing files. Read the copied `dependencies.json` and add only the required official dependencies to the target app.',
      '',
      `Search terms: ${component.keywords.join(', ')}.`,
      '',
      `Exports: ${symbols.map((name) => `\`${name}\``).join(', ')}.`,
      '',
      '## Complete local source',
      '',
      ...component.sourceFiles.map(
        (path) => `- [${relative(component.source, path)}](${relative(component.source, path)})`,
      ),
      '',
      `API reference ID: \`${component.id}\`. In the bundled authoring registry its plain API document is \`${component.aiDocumentation}\`; use lookup to resolve the actual file path.`,
      '',
      '## Runnable reference examples',
      '',
      ...examples.map(
        (example) =>
          `- \`${example.id}\`: \`${example.path}\`. Read its source, then adjust relative imports when copying to the target app.`,
      ),
      '',
      'Use the [source template index](../INDEX.md) to find related components. Workspace projects also include recipe integration guides; the installed HTML Skill retains the complete API/example reference.',
      '',
    ];
    await writeFile(join(root, component.readme), lines.join('\n'));
    rows.push(
      `| [${component.name}](./${slug}/README.md) | ${component.description.replaceAll('|', '\\|').replaceAll('\n', ' ')} |`,
    );
  }
  const index = [
    '# Cobalt Extensions source templates',
    '',
    '<!-- Generated by tools/content.mjs; do not edit. -->',
    '',
    'General-purpose source templates built on Cobalt. Read the relevant complete implementation, types, CSS and local dependencies before reuse. Copy this source tree into `src/components/cobalt-extensions/`, adapt it in the target project, and use relative local imports.',
    '',
    'Never install `@openpencil/cobalt-extensions`; it is not a published dependency. Do not create package-name aliases or file dependencies for it. Only official Cobalt/React dependencies belong in the application package manifest. The copied `dependencies.json` lists their pinned baseline.',
    '',
    'For source-only reuse, run the HTML Skill script `cobalt-project.mjs copy-source --out <project>`. Workspace scaffolding already copies this directory. The source copy is editable; do not modify the original templates during a design task.',
    '',
    '| Component | Purpose |',
    '| --- | --- |',
    ...rows,
    '',
  ].join('\n');
  await writeFile(join(root, 'components/extensions/src/INDEX.md'), index);
  await writeFile(
    join(root, 'components/extensions/INDEX.md'),
    '# Cobalt source templates\n\nRead the [source index](./src/INDEX.md), then copy and adapt implementations in your project. Never install `@openpencil/cobalt-extensions`.\n',
  );
}
