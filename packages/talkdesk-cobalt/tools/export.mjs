/** Export the toolkit into the existing HTML Skill resource contract. */
import { cp, mkdir, readFile, readdir, writeFile, rm } from 'node:fs/promises';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
export const toolkitRoot = fileURLToPath(new URL('../', import.meta.url));
const ignored = new Set(['node_modules', 'dist', '__tests__', 'test', '.vite', '.DS_Store']);
async function copy(from, to) {
  await mkdir(dirname(to), { recursive: true });
  await cp(from, to, {
    recursive: true,
    filter: (path) => !path.split('/').some((part) => ignored.has(part)),
  });
}
export async function exportCobalt(destination) {
  const root = toolkitRoot;
  await (await import('./content.mjs')).buildContent();
  // Each path below is exclusively generated by this module.
  for (const path of [
    'templates/cobalt',
    'cobalt-reference',
    'references/cobalt',
    'references/cobalt-workspace.md',
  ]) {
    await rm(join(destination, path), { recursive: true, force: true });
  }
  await copy(join(root, 'templates'), join(destination, 'templates/cobalt'));
  await copy(join(root, '../html-prototype-review/scripts/html-review/chrome.css'), join(destination, 'scripts/html-review/chrome.css'));
  await copy(join(root, 'skill/references'), join(destination, 'references'));
  for (const name of [
    'cobalt-project.mjs',
    'inspect-business-source.mjs',
    'verify-workspace-shell.mjs',
    'cobalt-shell-adapter.mjs',
    'cobalt-lookup.mjs',
    'cobalt-source-templates.mjs',
  ]) {
    const text = await readFile(join(root, 'tools', name), 'utf8');
    await mkdir(join(destination, 'scripts'), { recursive: true });
    await writeFile(join(destination, 'scripts', name), text);
  }
  await copy(join(root, 'reference'), join(destination, 'cobalt-reference'));
  for (const path of [
    'components/extensions/src',
    'components/extensions/INDEX.md',
    'components/extensions/dependencies.json',
    'examples',
    'recipes',
    'content',
  ])
    await copy(join(root, path), join(destination, 'cobalt-reference', path));
  await copy(join(root, 'registry'), join(destination, 'cobalt-reference/registry'));
  const files = {};
  async function index(dir, prefix = '') {
    for (const entry of (await readdir(dir, { withFileTypes: true })).toSorted((a, b) =>
      a.name.localeCompare(b.name),
    )) {
      const name = join(prefix, entry.name);
      if (name === 'bundle.json') continue;
      if (entry.isSymbolicLink()) throw new Error(`Unexpected resource symlink: ${name}`);
      if (entry.isDirectory()) await index(join(dir, entry.name), name);
      else if (entry.isFile())
        files[name] = createHash('sha256')
          .update(await readFile(join(dir, entry.name)))
          .digest('hex');
    }
  }
  await index(join(destination, 'cobalt-reference'));
  await writeFile(
    join(destination, 'cobalt-reference/bundle.json'),
    JSON.stringify(
      {
        formatVersion: 1,
        revision: createHash('sha256').update(JSON.stringify(files)).digest('hex'),
        requires: { toolkit: 1 },
        files,
      },
      null,
      2,
    ) + '\n',
  );
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (!process.argv[2]) throw new Error('Pass an HTML Skill output directory');
  await exportCobalt(resolve(process.argv[2]));
}
